const { test } = require('node:test')
const assert = require('node:assert/strict')
const { startupReducer, initialStartupState, STARTUP_TIMEOUT_MS, FONT_TIMEOUT_MS } = require(process.env.STARTUP_TEST_MODULE)
const { withStorageDeadline, StorageUnavailableError, STORAGE_TIMEOUT_MS } = require(process.env.STORAGE_TEST_MODULE)

test('launch bounds leave room for storage, the existing 10s /me check and cache write', () => {
  assert.equal(FONT_TIMEOUT_MS, 5000)
  assert.equal(STORAGE_TIMEOUT_MS, 5000)
  assert.ok(STARTUP_TIMEOUT_MS > STORAGE_TIMEOUT_MS * 3 + 10000)
})
test('a real ready destination resolves immediately, and finish is permanent for that mount', () => {
  const ready = startupReducer(initialStartupState, { type:'ready' })
  assert.equal(ready.phase, 'finished')
  for (const type of ['ready','failed','retry']) assert.equal(startupReducer(ready, { type }), ready)
})
test('a preparation failure is finite and never auto-retries', () => {
  const failed = startupReducer(initialStartupState, { type:'failed' })
  assert.equal(failed.phase, 'failed')
  assert.equal(failed.failures, 1)
  assert.equal(startupReducer(failed, { type:'ready' }), failed)
  assert.equal(startupReducer(failed, { type:'failed' }), failed)
})
test('retry is single-flight; replaced attempts cannot resolve it', () => {
  let state = startupReducer(initialStartupState, { type:'failed' })
  state = startupReducer(state, { type:'retry' })
  assert.equal(state.phase, 'retrying')
  assert.equal(state.attempt, 1)
  assert.equal(startupReducer(state, { type:'retry' }), state)
  assert.equal(startupReducer(state, { type:'prepared', attempt:0 }), state)
  assert.equal(startupReducer(state, { type:'retry-failed', attempt:0 }), state)
  assert.equal(startupReducer(state, { type:'ready' }), state)
  assert.equal(startupReducer(state, { type:'prepared', attempt:1 }).phase, 'preparing')
})
test('a repeated failed retry retains a failed state and a failure count for both actions', () => {
  let state = startupReducer(initialStartupState, { type:'failed' })
  state = startupReducer(state, { type:'retry' })
  state = startupReducer(state, { type:'retry-failed', attempt:1 })
  assert.equal(state.phase, 'failed')
  assert.equal(state.failures, 2)
  state = startupReducer(state, { type:'retry' })
  state = startupReducer(state, { type:'prepared', attempt:2 })
  assert.equal(startupReducer(state, { type:'ready' }).phase, 'finished')
})
test('storage preserves absent versus unavailable, with no credential deletion as a side effect', async () => {
  assert.equal(await withStorageDeadline(async () => null), null)
  assert.equal(await withStorageDeadline(async () => 'stored-value'), 'stored-value')
  await assert.rejects(withStorageDeadline(async () => { throw new Error('native failure') }), StorageUnavailableError)
})
test('stuck native storage finishes in recovery; a late result cannot resolve the timed out attempt', async t => {
  t.mock.timers.enable({ apis:['setTimeout'] })
  let complete
  const native = new Promise(resolve => { complete = resolve })
  const result = withStorageDeadline(() => native)
  const rejected = assert.rejects(result, StorageUnavailableError)
  t.mock.timers.tick(STORAGE_TIMEOUT_MS)
  await rejected
  complete('late-value')
  await Promise.resolve()
  await assert.rejects(result, StorageUnavailableError)
})
