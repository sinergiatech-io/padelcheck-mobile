// Bundle the pinned Leaflet distribution locally; no JavaScript is fetched by the WebView.
const fs = require('node:fs'), path = require('node:path')
const root = path.resolve(__dirname, '..'), leaflet = path.join(root, 'node_modules/leaflet')
if (JSON.parse(fs.readFileSync(path.join(leaflet, 'package.json'), 'utf8')).version !== '1.9.4') throw Error('Review map vendor before changing Leaflet version')
const output = path.join(root, 'src/features/club/venues/map-vendor.ts')
fs.mkdirSync(path.dirname(output), { recursive: true })
fs.writeFileSync(output, '// Generated by scripts/build-venue-map.cjs. Leaflet 1.9.4, BSD-2-Clause; see leaflet-license.txt.\n' +
  'export const leafletScript = ' + JSON.stringify(fs.readFileSync(path.join(leaflet, 'dist/leaflet.js'), 'utf8')) + '\n' +
  'export const leafletStyles = ' + JSON.stringify(fs.readFileSync(path.join(leaflet, 'dist/leaflet.css'), 'utf8')) + '\n')
fs.copyFileSync(path.join(leaflet, 'LICENSE'), path.join(path.dirname(output), 'leaflet-license.txt'))
